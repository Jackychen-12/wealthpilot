def lookup(word: str) -> tuple[str, tuple[str, str, tuple[str, ...]]] | None:
    """找一个词：先按名字和别名精确找，再按包含关系找。"""
    key = (word or "").strip().lower().replace(" ", "")
    if not key:
        return None
    norm = lambda s: s.lower().replace(" ", "")  # noqa: E731
    for name, entry in TERMS.items():
        if key == norm(name) or key in {norm(a) for a in entry[2]}:
            return name, entry
    for name, entry in TERMS.items():
        if key in norm(name) or any(key in norm(a) for a in entry[2]):
            return name, entry
    return None


def explain(word: str = "") -> str:
    """给人看的解释。不带词就列出全部词条的名字。"""
    found = lookup(word)
    if found:
        name, (plain, how, aliases) = found
        return f"{name}：{plain}\n{how}" + (f"\n也叫：{'、'.join(aliases)}" if aliases else "")
    head = f"没有「{word.strip()}」这个词条。" if word.strip() else ""
    return head + "能解释的词：" + "、".join(TERMS)


def as_list() -> list[dict]:
    return [{"term": name, "plain": plain, "how": how, "aliases": list(aliases)} for name, (plain, how, aliases) in TERMS.items()]


